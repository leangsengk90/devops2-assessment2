SEED = 20261015
P = {  # model parameters (researcher assumptions, stated in Section 3.7.1)
    "resources": RESOURCES,
    "console_median_s": 35.0,      # median hands-on console time to create one resource
    "console_sigma": 0.45,         # log-normal spread of per-resource time
    "rework_prob": 0.02,           # chance a resource has to be corrected and redone
    "wait_mean_s": 480.0,          # unavoidable waiting (NAT gateways, load balancer, services) per build
    "wait_sd_s": 60.0,
    "learning_first": 1.15,        # first run 15% slower than the long-run level
    "learning_rate": 0.25,         # exponential decay of the learning effect per run
    "attr_error_prob": 0.005,      # chance that a manually recreated resource differs from the baseline
    "runs": 10,
}


def simulate_manual(p, rng):
    rows = []
    for k in range(1, p["runs"] + 1):
        learn = 1 + (p["learning_first"] - 1) * math.exp(-p["learning_rate"] * (k - 1))
        t = rng.lognormal(math.log(p["console_median_s"]), p["console_sigma"], p["resources"])
        redo = rng.random(p["resources"]) < p["rework_prob"]
        hands_on = (t.sum() + t[redo].sum()) * learn
        wait = max(0.0, rng.normal(p["wait_mean_s"], p["wait_sd_s"]))
        errors = int((rng.random(p["resources"]) < p["attr_error_prob"]).sum())
        rows.append({"run": k, "hands_on_s": round(hands_on), "wait_s": round(wait), "full_create_s": round(hands_on + wait),
                     "reworked_resources": int(redo.sum()), "rebuild_attr_errors": errors, "rebuild_success": int(errors == 0)})
    return pd.DataFrame(rows)


