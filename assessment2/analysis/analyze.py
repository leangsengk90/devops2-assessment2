def describe(x):
    x = np.asarray(x, dtype=float)
    x = x[~np.isnan(x)]          # one start-up (run 14, finance) has no recorded steady-state event
    n = len(x)
    sd = x.std(ddof=1)
    t = stats.t.ppf(0.975, n - 1)
    sw = stats.shapiro(x)
    return {"n": n, "mean": x.mean(), "sd": sd, "median": float(np.median(x)), "min": x.min(), "max": x.max(),
            "ci_low": x.mean() - t * sd / math.sqrt(n), "ci_high": x.mean() + t * sd / math.sqrt(n),
            "cv_pct": 100 * sd / x.mean(), "skew": float(stats.skew(x, bias=False)),
            "kurtosis": float(stats.kurtosis(x, bias=False)), "shapiro_W": float(sw[0]), "shapiro_p": float(sw[1])}


def compare(a, b):
    a, b = np.asarray(a, float), np.asarray(b, float)
    welch = stats.ttest_ind(a, b, equal_var=False)
    mw = stats.mannwhitneyu(a, b, alternative="two-sided")
    n1, n2 = len(a), len(b)
    sp = math.sqrt(((n1 - 1) * a.var(ddof=1) + (n2 - 1) * b.var(ddof=1)) / (n1 + n2 - 2))
    g = (a.mean() - b.mean()) / sp * (1 - 3 / (4 * (n1 + n2) - 9))
    se = math.sqrt((n1 + n2) / (n1 * n2) + g ** 2 / (2 * (n1 + n2)))
    v1, v2 = a.var(ddof=1) / n1, b.var(ddof=1) / n2
    df = (v1 + v2) ** 2 / (v1 ** 2 / (n1 - 1) + v2 ** 2 / (n2 - 1))
    return {"diff_mean": a.mean() - b.mean(), "ratio": b.mean() / a.mean(), "welch_t": float(welch.statistic), "welch_df": df,
            "welch_p": float(welch.pvalue), "mw_U": float(mw.statistic), "mw_p": float(mw.pvalue),
            "hedges_g": g, "g_ci_low": g - 1.96 * se, "g_ci_high": g + 1.96 * se}


def wilson(k, n, z=1.96):
    p = k / n
    den = 1 + z ** 2 / n
    c = (p + z ** 2 / (2 * n)) / den
    h = z * math.sqrt(p * (1 - p) / n + z ** 2 / (4 * n ** 2)) / den
    return {"k": k, "n": n, "p": p, "low": max(0.0, c - h), "high": min(1.0, c + h)}


